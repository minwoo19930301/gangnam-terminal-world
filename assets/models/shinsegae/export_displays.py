"""Blender CLI: blender -b upper-floor-displays.blend -P export_displays.py."""
from pathlib import Path
import bpy
import json
from mathutils import Vector

OUT = Path(__file__).resolve().parent

def sRGB(mat):
    color = 0
    for v in mat.diffuse_color[:3]:
        s = 12.92*v if v <= .0031308 else 1.055*v**(1/2.4)-.055
        color = (color << 8) | round(255*min(1,max(0,s)))
    return color

deps=bpy.context.evaluated_depsgraph_get()
data={}
for group in bpy.data.collections:
    key=group.get('display_key')
    if not key: continue
    pos=[]; faces=[]; index={}
    for src in sorted(group.all_objects,key=lambda o:o.name):
        if src.type != 'MESH': continue
        obj=src.evaluated_get(deps)
        mesh=obj.to_mesh()
        try:
            base=Vector(group['export_origin']); idx=[]
            for v in mesh.vertices:
                xyz=tuple(round(1000*q) for q in obj.matrix_world @ v.co - base)
                if xyz not in index:
                    index[xyz]=len(pos);pos.append(xyz)
                idx.append(index[xyz])
            mesh.calc_loop_triangles()
            for poly in mesh.polygons:
                col=sRGB(mesh.materials[poly.material_index])
                if len(poly.vertices)<=4:
                    faces.append([col,*[idx[i] for i in poly.vertices]])
                else:
                    faces.extend([[col,*[idx[i] for i in t.vertices]] for t in mesh.loop_triangles if t.polygon_index==poly.index])
        finally:
            obj.to_mesh_clear()
    data[key]={'mm':pos,'faces':faces}
with (OUT/'displays.js').open('w') as f:
    f.write('// Generated by export_displays.py from upper-floor-displays.blend. Local X spans the storefront, Y faces into the shop, Z is up.\nexport const displays = {\n')
    for key,value in data.items():
        f.write(f'  "{key}":'+json.dumps(value,separators=(',',':'))+',\n')
    f.write('};\n')
