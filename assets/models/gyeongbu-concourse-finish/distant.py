"""Distant native mesh and its small, texture-free browser representation."""
import base64
import math
import struct


def make_proxy(Part,edge,swatches,srgb,here):
    p=Part('Distant silhouette · stone bands, ceiling fields and wall return')
    p.rect(50.2,21.9,62.2,35.7,.058,1,.94)
    for i,j,k,l in [(1,1,8,4),(3,6,13,7),(2,13,13,16),(9,18,18,19)]:
        p.rect(50.2+i*.6,21.9+j*.6,50.2+k*.6,21.9+l*.6,.061,4,.92)
    p.rect(58.25,27,58.55,35.7,.071,5,(.85,.68,.39))
    p.rect(50.2,26.70,62.2,27.0,.071,5,(.85,.68,.39))
    for i in range(16):
        a,b=i/16,(i+1)/16
        ua,ub=edge(a),edge(b)
        va,vb=27+6*a,27+6*b
        for xa,xb,ya,yb,swatch,tint in [(54,54,ua-.09,ub-.09,5,.87),
                                           (ua-.09,ub-.09,ua+.055,ub+.055,8,1),
                                           (ua+.055,ub+.055,62,62,6,.97)]:
            h=4.61 if swatch!=6 else 4.75
            p.face([(xa,va,h),(ya,va,h),(yb,vb,h),(xb,vb,h)],swatch,(0,0,-1),tint)
    for i in range(12):
        a,b=54+i*8/12,54+(i+1)*8/12
        def strip(x):return 24.98+1.13*math.exp(-((x-58.8)/2.25)**4)
        va,vb=strip(a),strip(b)
        for ya,yb,za,zb,h,swatch,tint in [(23.04,23.04,va,vb,3.27,6,.97),(va,vb,va+.12,vb+.12,3.18,8,1),
                                             (va+.12,vb+.12,26.998,26.998,3.175,5,.86)]:
            p.face([(a,ya,h),(b,yb,h),(b,zb,h),(a,za,h)],swatch,(0,0,-1),tint)
    p.rect(52.26,26.87,55.00,30.60,3.31,5,.91,down=True)
    p.rect(52.26,30.60,53.43,32.97,3.31,5,.91,down=True)
    p.face([(54.63,27.91,.07),(54.63,30.08,.07),(54.63,30.08,3.3),(54.63,27.91,3.3)],5,(1,0,0),.85)
    p.face([(54.635,28.00,.14),(54.635,29.96,.14),(54.635,29.96,2.15),(54.635,28.00,2.15)],7,(1,0,0),.35)
    # Keep the Blender proxy editable. Ship its centimetre vertices / linear
    # RGB in the place module to avoid an additional low-LOD network request.
    unique={}
    packed=bytearray()
    indices=[]
    offset=0
    for face in p.faces:
        current=[]
        for j,index in enumerate(face):
            (u,v),light=p.loops[offset+j]
            slot=min(3,int(u*4))+4*min(1,int(v*2))
            tint=swatches[slot]
            if slot==6 and u>(2+.985)/4 and v>(1+.985)/2:tint=(255,253,249)
            colour=[round(srgb(c/255)*k*255) for c,k in zip(tint,light[:3])]
            x,minus_z,y=p.vertices[index]
            key=(round(x*1000),round(y*1000),round(-minus_z*1000),*colour)
            if key not in unique:
                unique[key]=len(unique)
                packed+=struct.pack('<3h3B',*key)
            current.append(unique[key])
        offset+=len(face)
        for i in range(1,len(face)-1):indices.extend((current[0],current[i],current[i+1]))
    encode=lambda data:base64.b64encode(data).decode('ascii')
    raw_indices=struct.pack('<'+'H'*len(indices),*indices)
    (here/'proxy.js').write_text('// Generated by Blender build.py from the editable distant silhouette.\n'+
         "export const vertices='"+encode(packed)+"';\nexport const triangles='"+encode(raw_indices)+"';\n")
    return p
