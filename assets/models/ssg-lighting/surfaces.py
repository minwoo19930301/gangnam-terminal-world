"""Original whitewashed timber, grazing light, and compact PBR finish atlas."""

import bpy
import numpy as np

W, H = 1024, 768
TIMBER = (3, 3, 1020, 382)
WALL = (3, 392, 756, 752)
COLOR = "Lightnow · reclaimed timber and wall"
NORMAL = "Lightnow · sawn plank pores"
ORM = "Lightnow · surface response"


def create_image(name, values, data=False):
    img = bpy.data.images.new(name, width=W, height=H, alpha=False)
    if data:
        img.colorspace_settings.name = "Non-Color"
    rgba = np.ones((H,W,4), dtype=np.float32)
    rgba[:,:,:3] = values
    img.pixels.foreach_set(rgba.ravel());img.pack()
    return img


def maps():
    rng = np.random.default_rng(117)
    color=np.ones((H,W,3),np.float32)
    normal=np.empty_like(color);normal[:]=(.5,.5,1)
    orm=np.empty_like(color);orm[:]=(1,.54,.04)
    x0,y0,x1,y1=TIMBER
    yy,xx=np.mgrid[y0:y1+1,x0:x1+1]
    y=(yy-y0)/(y1-y0);x=(xx-x0)/(x1-x0)
    plank=np.minimum((y*7).astype(int),6)
    knot=np.zeros(x.shape)
    flow=y*86+.21*np.sin(x*16+plank*1.12)+.54*np.sin(x*3.24+plank*2.1)
    for cx,cy,r in [(.23,.361,.052),(.77,.709,.038),(.62,.151,.041),(.055,.883,.05),(.89,.486,.038)]:
        e=((x-cx)/r)**2+((y-cy)/(.4*r))**2
        flow+=np.exp(-e)*.85
        knot+=.07*np.exp(-e*1.7)*(.45+.55*np.cos(e*2.5))
    lines=np.clip((np.sin(flow*2*np.pi)+.35*np.sin((flow+.14)*4*np.pi)-.29),0,1)**3
    worn=np.maximum(0,np.cos(2*np.pi*(flow*.31+np.sin(x*9+plank*.7)*.35))-.52)
    fine=np.sin(flow*2*np.pi*6+.32*np.sin(x*84))*rng.normal(.004,.001,x.shape)
    sample=rng.normal(0,.006,x.shape)+fine-.034*lines-.085*worn-knot
    bases=np.array([[.845,.831,.755],[.889,.870,.792],[.824,.814,.733],[.862,.848,.771],[.895,.876,.804],[.838,.823,.747],[.878,.864,.785]])
    surface=bases[plank]+np.array([.008,.014,.026])+sample[:,:,None]
    # Narrow whitewash marks and patches with broken lengths running parallel
    # to the timber. The grain remains independent of the specimen lamps.
    brush=np.zeros_like(x)
    for _ in range(112):
        cx,cy=rng.uniform(0,1,2);sx=rng.uniform(.012,.115);sy=rng.uniform(.0008,.0038)
        brush+=rng.uniform(.015,.062)*np.exp(-((x-cx)/sx)**6-((y-cy)/sy)**2)
    surface+=brush[:,:,None]
    # The fixed samples cast small contact shadows and bounce a warm pool
    # onto the lacquer. These diffuse cues do not allocate live scene lights.
    px=-.865+x*2.71;py=-.482+y*.964
    for cx,cy,s in [(-.46,.02,.12),(.22,.07,.084),(.75,.025,.088),(1.46,.08,.074)]:
        rr=((px-cx)/(s*1.53))**2+((py-cy)/(s*1.2))**2
        surface-=.046*np.exp(-rr*1.9)[:,:,None]
    pool=np.exp(-((px-1.38)/.275)**2-((py-.065)/.20)**2)
    surface+=pool[:,:,None]*np.array([.025,.021,.011])
    # Generated byte images hold encoded sRGB. The glTF base colour sampler
    # converts the stored texels to scene-linear on read.
    color[y0:y1+1,x0:x1+1]=np.clip(surface,0,1)
    dy,dx=np.gradient(-.46*lines-.22*worn-.23*knot+.15*brush+.085*rng.normal(0,1,x.shape))
    n=np.stack((-.33*dx,-.33*dy,np.ones_like(dx)),axis=2);n/=np.linalg.norm(n,axis=2)[:,:,None]
    normal[y0:y1+1,x0:x1+1]=(n+1)/2
    orm[y0:y1+1,x0:x1+1,1]=.42+.13*lines+.11*worn-.08*brush
    orm[y0:y1+1,x0:x1+1,2]=.015
    x0,y0,x1,y1=WALL
    yy,xx=np.mgrid[y0:y1+1,x0:x1+1]
    u=(xx-x0)/(x1-x0);v=(yy-y0)/(y1-y0)
    spill=.052*np.exp(-((u-.44)/.25)**2-((v-.38)/.38)**2)+.044*np.exp(-((u-.18)/.16)**2-((v-.46)/.25)**2)
    paint=np.stack((.866+.78*spill,.863+.91*spill,.842+spill),axis=2)
    color[y0:y1+1,x0:x1+1]=paint;orm[y0:y1+1,x0:x1+1,1]=.84
    for r in range(16):
        for m in range(16):
            orm[506+r*16:522+r*16,768+m*16:784+m*16]=(1,r/15,m/15)
    return create_image(COLOR,color),create_image(NORMAL,normal,True),create_image(ORM,orm,True)


def tile_for_mat(mat):
    p=mat.node_tree.nodes.get("Principled BSDF")
    rough=p.inputs["Roughness"].default_value
    metal=p.inputs["Metallic"].default_value
    return ((776+16*round(metal*15))/W,(514+16*round(rough*15))/H)


def coord(box,x,y):
    x0,y0,x1,y1=box
    return ((x0+.5+(x1-x0)*max(0,min(1,x)))/W,(y0+.5+(y1-y0)*max(0,min(1,y)))/H)


def uv_for(obj, special=None):
    me=obj.data
    if me.uv_layers:
        uv=me.uv_layers.active
        uv.name="Lightnow UV"
    else:
        uv=me.uv_layers.new(name="Lightnow UV")
    material=obj.data.materials[0]
    point=tile_for_mat(material)
    for loop in me.loops:
        if special:
            v=obj.matrix_world@me.vertices[loop.vertex_index].co
            if special=="timber":
                value=coord(TIMBER,(v.x+.865)/2.71,(v.y+.482)/.964)
            else:
                value=coord(WALL,v.x/5.15+.5,v.z/3.14)
        else:
            value=point
        uv.data[loop.index].uv=value


def textured(mat,images,tint=False):
    nodes=mat.node_tree.nodes;links=mat.node_tree.links
    p=nodes.get("Principled BSDF")
    sample=[]
    for img in images:
        tex=nodes.new("ShaderNodeTexImage");tex.image=img;sample.append(tex)
    color=sample[0].outputs["Color"]
    if tint:
        extra=nodes.new("ShaderNodeVertexColor");extra.layer_name="Tint"
        mix=nodes.new("ShaderNodeMixRGB");mix.blend_type="MULTIPLY";mix.inputs[0].default_value=1
        links.new(color,mix.inputs[1]);links.new(extra.outputs["Color"],mix.inputs[2]);color=mix.outputs[0]
    links.new(color,p.inputs["Base Color"])
    norm=nodes.new("ShaderNodeNormalMap");links.new(sample[1].outputs["Color"],norm.inputs["Color"]);links.new(norm.outputs["Normal"],p.inputs["Normal"])
    sep=nodes.new("ShaderNodeSeparateRGB");links.new(sample[2].outputs["Color"],sep.inputs[0])
    links.new(sep.outputs["G"],p.inputs["Roughness"]);links.new(sep.outputs["B"],p.inputs["Metallic"])


def author_surfaces(collection):
    images=maps()
    bpy.context.view_layer.update()
    for obj in collection.objects:
        if obj.name.startswith("Plank top"):
            special="timber"
        elif obj.name=="Gallery backdrop":
            special="wall"
        else:
            continue
        obj["atlasSurface"]=special
        uv_for(obj,special)
        mat=obj.data.materials[0].copy();mat.name="Showroom · "+obj.name
        textured(mat,images);obj.data.materials[0]=mat
