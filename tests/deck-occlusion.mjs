import assert from 'node:assert/strict';
import * as THREE from 'three';
import {createDeckVisibility} from '../js/deck-visibility.js';

const eye=new THREE.PerspectiveCamera();eye.position.set(0,2,0);
const box=(x,y,z,a,b,c)=>new THREE.Box3(new THREE.Vector3(x,y,z),new THREE.Vector3(a,b,c));
const rect=(x,z,a,b)=>[[x,z],[a,z],[a,b],[x,b]];
const roof=createDeckVisibility();
roof.register({poly:rect(-10,-10,10,10),holes:[rect(2.8,-1,4.1,1)],y:0,eyeMin:.1,eyeMax:3.9});
roof.register({poly:rect(-10,-10,10,10).reverse(),holes:[rect(-4.2,-1,-2.7,1)],y:4,eyeMin:.1,eyeMax:3.9});
roof.update(eye);
assert.ok(roof.hides(box(-1,-5,-1,1,-4,1)));
assert.ok(roof.hides(box(-1,8,-1,1,10,1)));
assert.equal(roof.hides(box(-4,-1,-.5,9,-.17,.5)),false,'part intersects the opening');
assert.equal(roof.hides(box(5.6,-2,-.5,7.2,-1.88,.5)),false,'through the opening below');
assert.equal(roof.hides(box(-7.7,5.88,-.5,-5.65,6.11,.5)),false,'through the opening above');
assert.equal(roof.hides(box(-20,-.18,-3,-9,-.06,3)),false,'projection crosses the outside edge');
assert.equal(roof.hides(box(-1,-5,-1,1,.01,1)),false,'bounds intersect the slab');
const revisions=roof.revision;roof.update(eye);assert.equal(roof.revision,revisions);
eye.position.set(14,2,4);roof.update(eye);assert.equal(roof.active,false);
eye.position.set(0,2,0);roof.update(eye);assert.equal(roof.active,true);
roof.update(null);assert.equal(roof.active,false);
const notch=createDeckVisibility();notch.register({poly:[[-5,-5],[5,-5],[5,4],[.4,4],[.4,-1],[-.4,-1],[-.4,4],[-5,4]],holes:[],y:0,eyeMin:.1,eyeMax:6});
eye.position.set(-2,2,-2);notch.update(eye);
assert.equal(notch.hides(box(-1,-.5,-.2,1.5,-.2,.8)),false,'a concave notch enters the projected rectangle');
assert.ok(notch.hides(box(-3,-.7,-3,-2,-.3,-2)));
const diagonal=createDeckVisibility();
diagonal.register({poly:[[-5,-5],[5,-5],[5,5],[1,5],[0,4],[-5,0]],y:0,eyeMin:0.1,eyeMax:4});
eye.position.set(0,2,-2);diagonal.update(eye);
assert.ok(diagonal.hides(box(-2.6,-.1,.1,-2.4,-.09,.3)),'inside the AABB of a slanted boundary, outside the segment');
console.log('OK opaque floors and ceilings, holes, silhouette edges, partial overlaps, concave notch and return');
